#!/usr/bin/env python3
"""Generate CPU-usable cuda.hpp helpers and exact SDK Event flag operators."""
import argparse
from pathlib import Path
import re

from _files import write_if_changed
from generate_inline_helpers import bodies, license_for

ROOT = Path(__file__).resolve().parents[1]
SDK = ROOT / "upstream/opencv/modules/core/include/opencv2/core"


def generate():
    source = (SDK / "cuda.inl.hpp").read_text()
    helpers = list(bodies(source, ["createContinuous", "ensureSizeIsEnough", "swap"], False))
    assert len(helpers) == 6, len(helpers)
    result = "// Generated by tools/generate_cuda_helpers.py; original SDK bodies retained.\n"
    result += license_for(source, "core/cuda.inl.hpp")
    result += '''namespace opencv_m_cuda_up {
inline constexpr auto create = static_cast<void (*)(int, int, int, cv::OutputArray)>(&cv::cuda::createContinuous);
inline constexpr auto ensure = static_cast<void (*)(int, int, int, cv::OutputArray)>(&cv::cuda::ensureSizeIsEnough);
}
export namespace cv { namespace cuda { inline namespace opencv_m_cuda_repl {
'''
    prefix = "template<class _D = void> requires ::cv::opencv_m_repl::opencv_m_pick<_D> inline "
    functions = [
        ("void createContinuous(int rows, int cols, int type, OutputArray arr)",
         "{ ::opencv_m_cuda_up::create(rows, cols, type, arr); }"),
        ("void ensureSizeIsEnough(int rows, int cols, int type, OutputArray arr)",
         "{ ::opencv_m_cuda_up::ensure(rows, cols, type, arr); }"),
    ]
    for _, head, body in helpers:
        for name in ("createContinuous", "ensureSizeIsEnough"):
            body = re.sub(r"(?<![\w:])" + name + r"\(", "::cv::cuda::opencv_m_cuda_repl::" + name + "(", body)
        functions.append((" ".join(head.split()), body))
    result += "\n".join(prefix + head + ";" for head, _ in functions) + "\n\n"
    result += "\n\n".join(prefix.replace("_D = void", "_D") + head + "\n" + body for head, body in functions)
    result += "\n} } } // cv::cuda::opencv_m_cuda_repl\n"

    # Expand the pinned macro definitions rather than transcribing flag algebra.
    source = (SDK / "cvdef.h").read_text()
    definitions = {}
    for match in re.finditer(r"(?m)^#define (__CV_ENUM_FLAGS_\w+)\(([^\n)]*)\)", source):
        end = source.index("\n", match.end()) + 1
        while source[source.rfind("\n", 0, end - 1) + 1:end].rstrip().endswith("\\"):
            end = source.index("\n", end) + 1
        body = source[match.end():end].replace("\\\n", "\n").strip()
        definitions[match[1]] = (match[2].split(","), body)
    invocation = source[source.index("#define CV_ENUM_FLAGS(EnumType)"):]
    invocation = invocation[:invocation.index("/****************************************************************")]
    operators = re.findall(r"(__CV_ENUM_FLAGS_\w+)\s*\(([^)]+)\)", invocation)
    assert len(operators) == 10, len(operators)
    cuda_header = (SDK / "cuda.hpp").read_text()
    assert "CV_ENUM_FLAGS(Event::CreateFlags)" in cuda_header
    result += license_for(source, "core/cvdef.h")
    result += "export namespace cv { namespace cuda { inline namespace opencv_m_cuda_repl {\n"
    for name, arguments in operators:
        parameters, body = definitions[name]
        values = [value.strip().replace("EnumType", "Event::CreateFlags") for value in arguments.split(",")]
        assert len(values) == len(parameters)
        for parameter, value in zip(parameters, values):
            body = re.sub(r"\b" + parameter.strip() + r"\b", value, body)
        assert body.startswith("static inline "), body
        result += prefix + body.removeprefix("static inline ") + "\n\n"
    result += "} } } // cv::cuda::opencv_m_cuda_repl\n"
    return "\n".join(line.rstrip() for line in result.splitlines()) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = ROOT / "src/cuda_helpers.inc"
    content = generate()
    if args.check:
        assert output.read_text() == content, "Run python3 tools/generate_cuda_helpers.py"
    else:
        write_if_changed(output, content)


if __name__ == "__main__":
    main()
