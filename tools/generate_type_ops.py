#!/usr/bin/env python3
"""Generate all 122 pinned types.hpp free operators with named-module linkage."""
import argparse
from pathlib import Path
import re

from _files import write_if_changed
from generate_persistence import braced_end

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = (ROOT / "upstream/opencv/modules/core/include/opencv2/core/types.hpp").read_text()
    pattern = re.compile(r"(?m)^(?:template<([^\n>]+)>\s*)?static inline\s+([^{};]+?)\s*\{")
    functions = []
    for match in pattern.finditer(source):
        head = " ".join(match[2].split())
        if not re.search(r"\boperator\s*[^a-zA-Z\s]", head):
            continue
        opening = match.end() - 1
        body = source[opening:braced_end(source, opening)]
        if match[1]:
            template = match[1]
            assert template == "typename _Tp", template
            constraint = "opencv_m_pick<_Tp>"
        else:
            template = "class _D = void"
            constraint = "opencv_m_pick<_D>"
            # SDK Range operators are non-template/TU-local. Qualified calls
            # prevent their priority over the module's constrained adapters.
            body = body.replace("!(r1 == r2)", "!(::cv::opencv_m_repl::operator==(r1, r2))")
            body = body.replace("r1 = r1 & r2;", "r1 = ::cv::opencv_m_repl::operator&(r1, r2);")
            body = body.replace("return r1 + (-delta);", "return ::cv::opencv_m_repl::operator+(r1, -delta);")
        prefix = f"template<{template}> requires {constraint} inline "
        definition = prefix.replace("_D = void", "_D") + head
        functions.append((prefix + head, definition, body))
    assert len(functions) == 122, len(functions)
    result = "// Generated by tools/generate_type_ops.py; pinned SDK operator bodies retained.\n"
    result += source[:source.index("#ifndef")]
    result += "export namespace cv { inline namespace opencv_m_repl {\n"
    result += "\n".join(declaration + ";" for declaration, _, _ in functions) + "\n\n"
    result += "\n\n".join(definition + "\n" + body for _, definition, body in functions)
    result += "\n} } // cv::opencv_m_repl\n"
    output = ROOT / "src/type_ops.inc"
    if args.check:
        assert output.read_text() == result, "Run python3 tools/generate_type_ops.py"
    else:
        write_if_changed(output, result)


if __name__ == "__main__":
    main()
