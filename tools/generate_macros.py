#!/usr/bin/env python3
"""Generate typed OpenCV type/layout macro mappings from pinned headers.

Declaration/annotation/control-flow macros remain available through the textual
side header. This module maps values and pure type/layout calculations only.
"""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def generate():
    header = ROOT / "upstream/opencv/modules/core/include/opencv2/core/hal/interface.h"
    constants = [name for name, _ in re.findall(
        r"^#define (CV_\w+)[ \t]+([^\n]+)", header.read_text(), re.M)
        if name not in {"CV_USRTYPE1", "CV_MAKE_TYPE"}]
    constants += ["CV_VERSION_MAJOR", "CV_VERSION_MINOR", "CV_VERSION_REVISION",
                  "CV_VERSION", "CV_VERSION_STATUS", "CV_PI", "CV_2PI", "CV_LOG2",
                  "CV_MAX_DIM", "CV_MAT_CN_MASK", "CV_MAT_TYPE_MASK",
                  "CV_MAT_CONT_FLAG_SHIFT", "CV_MAT_CONT_FLAG", "CV_SUBMAT_FLAG_SHIFT",
                  "CV_SUBMAT_FLAG", "CV_AUTOSTEP"]
    hal_headers = ["features/hal/interface.h", "imgproc/hal/interface.h"]
    for relative in hal_headers:
        module = relative.split("/", 1)[0]
        source = (ROOT / "upstream/opencv/modules" / module / "include/opencv2" / relative).read_text()
        constants += re.findall(r"^#define (CV_HAL_\w+)[ \t]+[^\n]+", source, re.M)
    unary = ["CV_MAT_DEPTH", "CV_IS_INT_TYPE", "CV_IS_FLOAT_TYPE", "CV_MAT_CN",
             "CV_MAT_TYPE", "CV_IS_MAT_CONT", "CV_IS_CONT_MAT", "CV_ELEM_SIZE1", "CV_ELEM_SIZE"]
    unary += re.findall(r"^#define (CV_\w+C)\(n\)", header.read_text(), re.M)
    functions = {name: ("int value", "value") for name in unary}
    functions.update({name: ("int depth, int channels", "depth, channels")
                      for name in ("CV_MAKETYPE", "CV_MAKE_TYPE")})
    simd_constants = ["CV_SIMD", "CV_SIMD_WIDTH", "CV_SIMD_64F", "CV_SIMD_FP16",
                      "CV_SIMD128", "CV_SIMD128_CPP", "CV_SIMD128_64F", "CV_SIMD128_FP16",
                      "CV_SIMD256", "CV_SIMD256_64F", "CV_SIMD256_FP16",
                      "CV_SIMD512", "CV_SIMD512_64F", "CV_SIMD512_FP16", "CV_SIMD_SCALABLE"]
    lines = ["// Generated by tools/generate_macros.py; do not edit.", "module;",
             "#include <opencv2/core.hpp>", "#include <opencv2/core/version.hpp>",
             *[f"#include <opencv2/{path}>" for path in hal_headers],
             "#if defined(MCPP_FEATURE_SIMD)", "#include <opencv2/core/simd_intrinsics.hpp>", "#endif", "",
             "export module mcpplibs.mwrap.opencv.macros;", "",
             "namespace opencv_m_macro_detail {"]
    lines += [f"inline constexpr auto k_{name} = {name};" for name in constants]
    lines += ["#if defined(MCPP_FEATURE_SIMD)",
              *[f"inline constexpr auto k_{name} = {name};" for name in simd_constants], "#endif"]
    lines += [f"constexpr int k_{name}({params}) {{ return {name}({args}); }}"
              for name, (params, args) in functions.items()]
    lines += ["template<class A, class B, class C, class D>",
              "constexpr auto k_CV_FOURCC_MACRO(A a, B b, C c, D d) { return CV_FOURCC_MACRO(a, b, c, d); }"]
    # OpenCV 5.0.0's CV_IS_SUBMAT references an undefined CV_MAT_SUBMAT_FLAG.
    # Adapt that single typed mapping to the actual upstream Mat flag. The
    # optional raw side header retains the original upstream macro unchanged.
    lines += ["constexpr int k_CV_IS_SUBMAT(int flags) { return flags & CV_SUBMAT_FLAG; }", "}", ""]
    lines += [f"#undef {name}" for name in [*constants, *functions, "CV_IS_SUBMAT", "CV_FOURCC_MACRO"]]
    lines += ["#if defined(MCPP_FEATURE_SIMD)", *[f"#undef {name}" for name in simd_constants], "#endif"]
    lines += ["", "export namespace mcpplibs::mwrap::opencv::macros {"]
    lines += [f"inline constexpr auto {name} = opencv_m_macro_detail::k_{name};" for name in constants]
    lines += ["#if defined(MCPP_FEATURE_SIMD)",
              *[f"inline constexpr auto {name} = opencv_m_macro_detail::k_{name};" for name in simd_constants], "#endif"]
    lines += [f"constexpr int {name}({params}) {{ return opencv_m_macro_detail::k_{name}({args}); }}"
              for name, (params, args) in functions.items()]
    lines += ["template<class A, class B, class C, class D>",
              "constexpr auto CV_FOURCC_MACRO(A a, B b, C c, D d) { return opencv_m_macro_detail::k_CV_FOURCC_MACRO(a, b, c, d); }"]
    lines += ["// Repair the upstream 5.0.0 CV_MAT_SUBMAT_FLAG typo for the typed mapping.",
              "constexpr int CV_IS_SUBMAT(int flags) { return opencv_m_macro_detail::k_CV_IS_SUBMAT(flags); }", "}", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / "src/macros.cppm"
    content = generate()
    if args.check:
        if path.read_text() != content:
            raise SystemExit("src/macros.cppm is stale; run tools/generate_macros.py")
    else:
        path.write_text(content)
