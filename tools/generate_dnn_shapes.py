#!/usr/bin/env python3
"""Retain pinned DNN shape-helper bodies while adapting TU-local linkage."""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
source = (ROOT / "upstream/opencv/modules/dnn/include/opencv2/dnn/shape_utils.hpp").read_text()
body = source.split("//Slicing", 1)[1].split("CV__DNN_INLINE_NS_END", 1)[0]
# _Range remains the actual SDK class, exported in gen_exports/dnn.inc.
body, ranges = re.subn(r"struct _Range : public cv::Range\n\{.*?\n\};", "", body, flags=re.S)
assert ranges == 1
body, disabled = re.subn(r"#if 0.*?#endif", "", body, flags=re.S)
assert disabled == 1
body, anonymous = re.subn(r"namespace \{inline bool is_neg\(int i\) \{ return i < 0; \}\}", "", body)
assert anonymous == 1
body, templates = re.subn(r"template<typename _Tp>\nstatic inline", "template<typename _Tp> requires shape_pick<_Tp> inline", body)
assert templates == 3
body, functions = re.subn(r"static inline\s+", "template<class _D = void> requires shape_pick<_D> inline ", body)
assert functions == 17, functions
# Keep calls between helpers in this adapter, rather than referring from an
# exported template to the SDK's internal-linkage global-module functions.
for helper in ("shape", "toString", "normalize_axis"):
    body = re.sub(r"(?<![.\w:])" + helper + r"\(",
                  "::cv::dnn::CV__DNN_INLINE_NS::opencv_m_shape::" + helper + "(", body)
    # Definitions themselves must retain their unqualified declarator.
    body = re.sub(r"(inline (?:MatShape|std::string|int) )::cv::dnn::CV__DNN_INLINE_NS::opencv_m_shape::" + helper,
                  r"\1" + helper, body)
license_text = source[:source.index("#ifndef OPENCV_DNN_DNN_SHAPE_UTILS_HPP")]
result = ("// Generated by tools/generate_dnn_shapes.py. Included inside the exported shape adapter.\n"
          + license_text + body.strip() + "\n")
output = ROOT / "src/dnn_shapes.inc"
if args.check:
    assert output.read_text() == result, "Run python3 tools/generate_dnn_shapes.py"
else:
    output.write_text(result)
