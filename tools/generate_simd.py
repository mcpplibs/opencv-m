#!/usr/bin/env python3
"""Generate explicit exports of original baseline SIMD SDK entities."""
import argparse
import json
from pathlib import Path
import re

from _files import write_if_changed

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    surface = json.loads((ROOT / "port/api/simd-surface.json").read_text())
    assert surface["upstream-version"] == "5.0.0"
    result = "// Generated by tools/generate_simd.py; original SDK entities, no copied vector types.\n"
    result += "export namespace cv {\n"
    memory = surface["gcc-memory-bridges"]
    for name in surface["common"]:
        if name in memory:
            result += "#if !defined(__GNUC__) || defined(__clang__)\n"
        result += f"using ::cv::{name};\n"
        if name in memory:
            result += "#endif\n"
    for group, condition in (("sse2", "CV_SSE2"), ("fp16", "CV_SIMD128_FP16")):
        result += "#if " + condition + "\n"
        result += "\n".join(f"using ::cv::{name};" for name in surface[group]) + "\n#endif\n"
    result += "}\nexport namespace cv { namespace hal {\n"
    result += "\n".join(f"using ::cv::hal::{name};" for name in
                        ("StoreMode", "STORE_UNALIGNED", "STORE_ALIGNED", "STORE_ALIGNED_NOCACHE")) + "\n} }\n"
    result += "#if defined(__GNUC__) && !defined(__clang__)\n"
    result += "// GCC loses unaligned intrinsic typedef alignment through imported inline bodies.\n"
    result += "// Ordinary producer-compiled forwards preserve original SDK memory operations.\n"
    result += "namespace opencv_m_simd_up { using namespace ::cv;\n"
    wrappers = []
    for name, signatures in memory.items():
        seen = set()
        for signature in signatures:
            # The SDK forward declaration uses uint while its definition uses
            # unsigned int. Both denote one overload, not two adapters.
            signature = re.sub(r"\buint\b", "unsigned int", signature)
            if signature in seen:
                continue
            seen.add(signature)
            match = re.fullmatch(r"(.+?)\s*\((.*)\)", signature)
            assert match, signature
            returned, parameters = match.groups()
            types = [value.strip() for value in parameters.split(",")]
            assert not any("(" in value or re.search(r"\b_Tp\b", value) for value in types), signature
            params = [value + " a" + str(i) for i, value in enumerate(types)]
            public_params = list(params)
            if name == "v_store_interleave" and types[-1] == "hal::StoreMode":
                public_params[-1] += " = hal::STORE_UNALIGNED"
            arguments = ", ".join("a" + str(i) for i in range(len(types)))
            result += f"{returned} {name}({', '.join(params)}) {{ return ::cv::{name}({arguments}); }}\n"
            wrappers.append((returned, name, public_params, arguments))
    result += "}\nexport namespace cv { inline namespace opencv_m_simd_repl {\n"
    for returned, name, params, arguments in wrappers:
        result += "template<class _D = void> requires (sizeof(_D*) > 0)\n"
        result += f"inline {returned} {name}({', '.join(params)}) {{ return ::opencv_m_simd_up::{name}({arguments}); }}\n"
    result += "} }\n#endif\n"
    result += "export namespace cv { inline namespace opencv_m_simd_repl {\n"
    result += "template<class> inline constexpr bool pick = true;\n"
    for name in surface["legacy-adapters"]:
        function = name.replace("vx_", "v_", 1)
        result += "template<typename _Tp, typename _Tvec> requires pick<_Tp>\n"
        result += f"inline void {name}(_Tp* dst, const _Tvec& value) {{\n"
        result += f"#if defined(__GNUC__) && !defined(__clang__)\n::opencv_m_simd_up::{function}(dst, value);\n"
        result += f"#else\n::cv::{function}(dst, value);\n#endif\n}}\n"
    result += "} }\n"
    output = ROOT / "src/simd_exports.inc"
    if args.check:
        assert output.read_text() == result, "Run python3 tools/generate_simd.py"
    else:
        write_if_changed(output, result)


if __name__ == "__main__":
    main()
