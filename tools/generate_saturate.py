#!/usr/bin/env python3
"""Preserve all pinned upstream scalar-conversion overloads in the module adapter."""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = ROOT / "upstream/opencv/modules/core/include/opencv2/core/saturate.hpp"
    text = source.read_text()
    match = re.search(r"namespace cv\s*\{(.*)\n\} // cv", text, re.S)
    assert match, "Review upstream namespace layout before regeneration"
    body, count = re.subn(r"template<typename _Tp> static inline",
        "template<typename _Tp> requires opencv_m_pick<_Tp> inline", match[1])
    assert count == 13, "Review upstream source-type overloads before regeneration"
    # cvRound is TU-local. An ordinary private module function preserves its
    # exact platform implementation without exposing that entity in templates.
    body = body.replace("cvRound(v)", "::opencv_m_scalar_bridge::round32(v)")
    # Freeze the C-math lookup that upstream performed before other cv headers.
    body = re.sub(r"(?<![\w:])round\(", "::round(", body)
    result = ("// Generated by tools/generate_saturate.py; included inside cv::opencv_m_repl.\n"
              "// Upstream overloads/bodies are retained; only the module constraint and cvRound bridge differ.\n"
              + text[:text.index("#ifndef OPENCV_CORE_SATURATE_HPP")] + body.strip() + "\n")
    output = ROOT / "src/saturate_ops.inc"
    if args.check:
        assert output.read_text() == result, "Run python3 tools/generate_saturate.py"
    else:
        output.write_text(result)


if __name__ == "__main__":
    main()
