#!/usr/bin/env python3
"""Map the SDK TU-local ArUco float without an imported auto/APValue chain."""
import argparse
from pathlib import Path
import re

from _files import write_if_changed

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = (ROOT / "upstream/opencv/modules/objdetect/include/opencv2/objdetect/aruco_detector.hpp").read_text()
    match = re.search(r"static constexpr float DEFAULT_VALID_BIT_ID_THRESHOLD\{([0-9.]+f)\};", source)
    assert match, "Review the upstream constant declaration before regenerating"
    result = "// Generated by tools/generate_objdetect_constants.py; original SDK float token retained.\n"
    result += "// An explicit scalar avoids importing a deduced-auto initializer through a private SDK object.\n"
    result += "export namespace cv::aruco { inline namespace opencv_m_constants {\n"
    result += f"inline constexpr float DEFAULT_VALID_BIT_ID_THRESHOLD = {match[1]};\n"
    result += "} }\n"
    output = ROOT / "src/objdetect_constants.inc"
    if args.check:
        assert output.read_text() == result, "Run python3 tools/generate_objdetect_constants.py"
    else:
        write_if_changed(output, result)


if __name__ == "__main__":
    main()
