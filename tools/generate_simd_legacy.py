#!/usr/bin/env python3
"""Re-export original SDK legacy operators without copying template bodies."""
import argparse
from pathlib import Path
import re
from _files import write_if_changed

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
source = (ROOT / "upstream/opencv/modules/core/include/opencv2/core/hal/intrin_legacy_ops.h").read_text()
operators = re.findall(r"^(?:BIN_OP|BIN_A_OP|UN_OP)\(([^,]+),", source, re.M)
assert len(operators) == len(set(operators)) == 21, operators
result = "// Generated by tools/generate_simd_legacy.py; original SDK operator templates.\n"
result += "export namespace cv::hal {\n"
result += "".join("using ::cv::hal::operator" + op.strip() + ";\n" for op in operators)
result += "}\n"
output = ROOT / "src/simd_legacy_exports.inc"
if args.check:
    assert output.read_text() == result, "Run python3 tools/generate_simd_legacy.py"
else:
    write_if_changed(output, result)
