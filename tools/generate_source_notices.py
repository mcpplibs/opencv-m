#!/usr/bin/env python3
"""Retain embedded copyright/license comments from the pinned SDK in bundles.

Named LICENSE/COPYING/NOTICE files are deployed separately. This conservative
supplement collects C/C++ comment blocks throughout retained text sources, not
just leading preambles. Identical blocks are stored once with every location.
It preserves comment bytes and does not rewrite or classify upstream licenses.
"""
import argparse
from collections import defaultdict
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "port/licenses/UPSTREAM_SOURCE_NOTICES.txt"
TOKEN = re.compile(
    rb'(?P<block>/\*.*?\*/)|(?P<line>//[^\r\n]*(?:\r?\n[ \t]*//[^\r\n]*)*)'
    rb'|(?:u8|u|U|L)?R"(?P<delimiter>[^ ()\\\t\r\n]{0,16})\(.*?\)(?P=delimiter)"'
    rb'|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'',
    re.DOTALL,
)
TERMS = re.compile(rb"copyright|licen[cs]e|redistribution|SPDX-|public domain|patent", re.I)


def render():
    blocks = defaultdict(list)
    for path in sorted((ROOT / "upstream/opencv").rglob("*")):
        if not path.is_file() or "__pycache__" in path.parts:
            continue
        source = path.read_bytes()
        if b"\0" in source:
            continue
        for match in TOKEN.finditer(source):
            comment = match["block"] or match["line"]
            if comment is not None and TERMS.search(comment):
                line = source.count(b"\n", 0, match.start()) + 1
                blocks[comment].append(f"{path.relative_to(ROOT).as_posix()}:{line}")
    assert blocks, "No source notices found"
    result = bytearray(
        b"Generated by tools/generate_source_notices.py from retained OpenCV 5.0.0 sources.\n"
        b"Embedded copyright and license comments; original comment bytes preserved.\n"
        b"Named license files are distributed alongside this supplement.\n\n"
    )
    # Insertion order follows sorted source paths and comment positions.
    for comment, locations in blocks.items():
        result.extend(b"=" * 78 + b"\nSources:\n")
        result.extend(("\n".join(locations) + "\n\n").encode("utf-8"))
        result.extend(comment)
        result.extend(b"\n\n")
    return bytes(result), len(blocks), sum(map(len, blocks.values()))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result, unique, occurrences = render()
    if args.check:
        assert OUTPUT.read_bytes() == result, "Run python3 tools/generate_source_notices.py"
    elif not OUTPUT.exists() or OUTPUT.read_bytes() != result:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_bytes(result)
    print(f"Source notices: {unique} distinct blocks, {occurrences} locations, {len(result)} bytes")


if __name__ == "__main__":
    main()
