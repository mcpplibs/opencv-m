#!/usr/bin/env python3
"""Expand the pinned SDK's 49 Mat augmented-assignment macros for modules."""
import argparse
from pathlib import Path
import re

from _files import write_if_changed

ROOT = Path(__file__).resolve().parents[1]


def arguments(text):
    result, start, depth = [], 0, 0
    for position, char in enumerate(text):
        if char in "(<":
            depth += 1
        elif char in ")>":
            depth -= 1
        elif char == "," and depth == 0:
            result.append(text[start:position].strip())
            start = position + 1
    assert depth == 0, text
    return [*result, text[start:].strip()]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = (ROOT / "upstream/opencv/modules/core/include/opencv2/core/operations.hpp").read_text()
    entries = re.findall(r"(?m)^CV_MAT_AUG_OPERATOR(_TN|_T)?\s*\((.*)\)$", source)
    assert len(entries) == 49, len(entries)
    result = "// Generated by tools/generate_mat_aug_ops.py; SDK macro bodies/signatures retained.\n"
    result += source[:source.index("#ifndef")]
    result += "export namespace cv { inline namespace opencv_m_repl {\n"
    for kind, text in entries:
        values = arguments(text)
        op, body, left = values[:3]
        if kind == "_TN":
            assert len(values) == 3
            template, right = "typename _Tp, int m, int n", "Matx<_Tp,m,n>"
        elif kind == "_T":
            assert len(values) == 4
            template, right = "typename _Tp", values[3]
        else:
            assert len(values) == 4
            template, right = "class _D = void", values[3]
        constraint = "opencv_m_pick<_Tp>" if kind else "opencv_m_pick<_D>"
        for const in ("", "const "):
            result += (f"template<{template}> requires {constraint}\n"
                       f"inline {const}{left}& operator {op} ({const}{left}& a, const {right}& b)\n"
                       f"{{ {body}; return a; }}\n\n")
    result += "} } // cv::opencv_m_repl\n"
    path = ROOT / "src/mat_aug_ops.inc"
    if args.check:
        assert path.read_text() == result, "Run python3 tools/generate_mat_aug_ops.py"
    else:
        write_if_changed(path, result)


if __name__ == "__main__":
    main()
