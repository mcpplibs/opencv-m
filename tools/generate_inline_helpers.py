#!/usr/bin/env python3
"""Restore portable static-inline helpers from the pinned public SDK headers."""
import argparse
from pathlib import Path
import re

from _files import write_if_changed
from generate_persistence import braced_end

ROOT = Path(__file__).resolve().parents[1]
SDK = ROOT / "upstream/opencv/modules"


def bodies(source, names, templated):
    prefix = r"template<([^>\n]+)>\s+static inline\s+" if templated else r"(?:CV_WRAP\s+)?static inline\s+"
    pattern = re.compile(r"(?m)^" + prefix + r"([^;{}]+?)\s*\{")
    for match in pattern.finditer(source):
        head = match[2] if templated else match[1]
        name = re.search(r"\b(" + "|".join(names) + r")\s*\(", head)
        if not name:
            continue
        opening = match.end() - 1
        body = source[opening:braced_end(source, opening)]
        yield (match[1] if templated else "class _D = void"), head.strip(), body


def license_for(source, name):
    return "// SDK source: " + name + "\n" + source[:source.index("#ifndef")]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    core = "// Generated by tools/generate_inline_helpers.py; SDK bodies with module lookup/raw-array fixes.\n"
    expected = {"base.hpp": 6, "utility.hpp": 5, "types.hpp": 1, "mat.inl.hpp": 3}
    names = {"base.hpp": ["normL1", "normL2Sqr", "normInf"], "utility.hpp": ["isAligned"],
             "types.hpp": ["jaccardDistance"], "mat.inl.hpp": ["rawIn", "rawOut", "rawInOut"]}
    for header in expected:
        source = (SDK / "core/include/opencv2/core" / header).read_text()
        functions = list(bodies(source, names[header], True))
        assert len(functions) == expected[header], (header, len(functions))
        core += license_for(source, "core/" + header)
        core += "export namespace cv { inline namespace opencv_m_repl {\n"
        for template, head, body in functions:
            body = re.sub(r"(?<![\w:])isAligned<", "::cv::opencv_m_repl::isAligned<", body)
            body = re.sub(r"(?<![\w:])cv_abs(diff)?\(", r"::cv::cv_abs\1(", body)
            if header == "mat.inl.hpp" and " rawInOut(" in head:
                # OpenCV 5 omits `static` on the std::array member overload.
                # Calling through an instance supports that original member
                # and is equivalent for the existing static vector overload.
                declaration = (SDK / "core/include/opencv2/core/mat.hpp").read_text()
                assert re.search(r"template<typename _Tp, std::size_t _Nm>\s+_InputOutputArray rawInOut\(std::array<_Tp, _Nm>& arr\);", declaration)
                assert body.count("_InputOutputArray::rawInOut(v)") == 1
                body = body.replace("_InputOutputArray::rawInOut(v)", "_InputOutputArray().rawInOut(v)")
            core += f"template<{template}> requires opencv_m_pick<void>\ninline {head}\n{body}\n\n"
        core += "} } // cv::opencv_m_repl\n"

    source = (SDK / "imgproc/include/opencv2/imgproc.hpp").read_text()
    image = "// Generated by tools/generate_inline_helpers.py; SDK bodies retained.\n" + license_for(source, "imgproc.hpp")
    image += '''namespace opencv_m_imgproc_up {
inline constexpr auto wide_angle = static_cast<float (*)(cv::InputArray, cv::InputArray,
    cv::Size, int, int, cv::OutputArray, cv::OutputArray, cv::UndistortTypes, double)>(&cv::initWideAngleProjMap);
}
export namespace cv { inline namespace opencv_m_imgproc_repl {
template<class> inline constexpr bool pick = true;
template<class _D = void> requires pick<_D>
inline float initWideAngleProjMap(InputArray cameraMatrix, InputArray distCoeffs,
    Size imageSize, int destImageWidth, int m1type, OutputArray map1, OutputArray map2,
    UndistortTypes projType = PROJ_SPHERICAL_EQRECT, double alpha = 0) {
    return ::opencv_m_imgproc_up::wide_angle(cameraMatrix, distCoeffs, imageSize,
        destImageWidth, m1type, map1, map2, projType, alpha);
}
'''
    functions = list(bodies(source, ["morphologyDefaultBorderValue", "initWideAngleProjMap"], False))
    assert len(functions) == 2, len(functions)
    for template, head, body in functions:
        body = re.sub(r"(?<![\w:])initWideAngleProjMap\(", "::cv::opencv_m_imgproc_repl::initWideAngleProjMap(", body)
        image += f"template<{template}> requires pick<_D>\ninline {head}\n{body}\n\n"
    image += "} } // cv::opencv_m_imgproc_repl\n"

    source = (SDK / "imgcodecs/include/opencv2/imgcodecs.hpp").read_text()
    codecs = "// Generated by tools/generate_inline_helpers.py; SDK body retained.\n" + license_for(source, "imgcodecs.hpp")
    codecs += "export namespace cv { inline namespace opencv_m_imgcodecs_repl {\n"
    codecs += "template<class> inline constexpr bool pick = true;\n"
    functions = list(bodies(source, ["imwritemulti"], False))
    assert len(functions) == 1, len(functions)
    for template, head, body in functions:
        body = body.replace("return imwrite(", "return ::cv::imwrite(")
        codecs += f"template<{template}> requires pick<_D>\ninline {head}\n{body}\n"
    codecs += "} } // cv::opencv_m_imgcodecs_repl\n"
    # Global fast-math overload sets mix internal platform-specific functions
    # and external SoftFloat functions. Capture each exact original overload
    # before declaring constrained public forwards in a global inline namespace.
    fast_source = (SDK / "core/include/opencv2/core/fast_math.hpp").read_text()
    fast_signatures = re.findall(
        r"CV_INLINE int\s+(cv(?:Round|Floor|Ceil|IsNaN|IsInf))\s*\(\s*(float|double|int) value\s*\)",
        fast_source)
    assert len(fast_signatures) == 13, fast_signatures
    signatures = [(name, value_type + " value", "value") for name, value_type in fast_signatures]
    soft_source = (SDK / "core/include/opencv2/core/softfloat.hpp").read_text()
    soft_signatures = re.findall(
        r"CV_EXPORTS int\s+(cv(?:Round|Floor|Ceil))\(const cv::(softfloat|softdouble)&\s+a\);", soft_source)
    assert len(soft_signatures) == 6, soft_signatures
    signatures += [(name, "const cv::" + value_type + "& value", "value") for name, value_type in soft_signatures]
    cvdef_source = (SDK / "core/include/opencv2/core/cvdef.h").read_text()
    assert "CV_INLINE int CV_FOURCC(char c1, char c2, char c3, char c4)" in cvdef_source
    signatures.append(("CV_FOURCC", "char c1, char c2, char c3, char c4", "c1, c2, c3, c4"))
    fast = "// Generated by tools/generate_inline_helpers.py; exact SDK platform function forwards.\n"
    fast += "namespace opencv_m_fast_math_bridge {\n"
    for name, parameters, arguments in signatures:
        fast += f"int {name}({parameters}) {{ return ::{name}({arguments}); }}\n"
    fast += "}\nexport inline namespace opencv_m_fast_math_repl {\n"
    for name, parameters, arguments in signatures:
        fast += "template<class _D = void> requires ::cv::opencv_m_repl::opencv_m_pick<_D>\n"
        fast += f"inline int {name}({parameters}) {{ return ::opencv_m_fast_math_bridge::{name}({arguments}); }}\n"
    fast += "}\n"
    for name, content in [("portable_helpers.inc", core), ("imgproc_helpers.inc", image),
                          ("imgcodecs_helpers.inc", codecs), ("fast_math_helpers.inc", fast)]:
        output = ROOT / "src" / name
        if args.check:
            assert output.read_text() == content, "Run python3 tools/generate_inline_helpers.py: " + name
        else:
            write_if_changed(output, content)


if __name__ == "__main__":
    main()
